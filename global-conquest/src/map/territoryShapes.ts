import { MAP_VIEWBOX_HEIGHT, MAP_VIEWBOX_WIDTH } from "../router/pages/gameShared";

/** A point in the same local coordinate system as the map sprite (world-container pixels, 0,0 at top-left of risk0.png). */
export interface Point {
  x: number;
  y: number;
}

/** A point normalized to the source map image's dimensions — 0..1 on both axes, independent of render size. */
export interface NormalizedPoint {
  x: number;
  y: number;
}

export interface TerritoryShape {
  territoryId: string;
  /**
   * One entry per disconnected landmass belonging to this territory (e.g.
   * Indonesia's separate islands, or Japan/Kamchatka-style near-dateline
   * splits). Every polygon renders and hit-tests independently, but all of
   * them select/highlight as the same territory.
   */
  polygons: NormalizedPoint[][];
  /** Where the army-count badge is drawn, independent of any single polygon's centroid. */
  labelPosition: NormalizedPoint;
}

/**
 * Performance: hover is handled entirely inside TerritoryPolygon/TerritoryNode
 * via Pixi pointerover/pointerout listeners that trigger a local redraw —
 * it never sets React state, so panning the pointer across the board never
 * triggers a React re-render.
 */

/**
 * The pixel dimensions territoryShapes coordinates are normalized against.
 * Equal to risk0.png's actual dimensions, which is also exactly the size of
 * MapScene's worldContainer coordinate space — so denormalized points can be
 * used directly as world-container-local Pixi coordinates with no further
 * transform.
 */
export const MAP_SOURCE_WIDTH = MAP_VIEWBOX_WIDTH;
export const MAP_SOURCE_HEIGHT = MAP_VIEWBOX_HEIGHT;

export function normalizePoint(p: Point): NormalizedPoint {
  return { x: p.x / MAP_SOURCE_WIDTH, y: p.y / MAP_SOURCE_HEIGHT };
}

export function denormalizePoint(p: NormalizedPoint): Point {
  return { x: p.x * MAP_SOURCE_WIDTH, y: p.y * MAP_SOURCE_HEIGHT };
}

export function denormalizePolygons(polygons: NormalizedPoint[][]): Point[][] {
  return polygons.map((polygon) => polygon.map(denormalizePoint));
}

